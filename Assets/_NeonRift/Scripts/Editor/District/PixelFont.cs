        public static bool Has(char c) => Glyphs.ContainsKey(char.ToUpperInvariant(c));

        /// <summary>True if pixel (x, y) of the glyph is lit; y = 0 is the top row.</summary>
        public static bool Pixel(char c, int x, int y)
        {
            if (!Glyphs.TryGetValue(char.ToUpperInvariant(c), out var rows)) return false;
            return rows[y][x] == '#';
        }

        /// <summary>Width of <paramref name="text"/> in font pixels with one pixel of spacing.</summary>
        public static int Measure(string text) => text.Length == 0 ? 0 : text.Length * (Width + 1) - 1;
